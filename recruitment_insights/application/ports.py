"""Structural contracts for one transaction; services never open SQL connections.

Repositories return detached dictionaries. Only the unit of work commits or rolls
back; adapters must not commit within repository methods.
"""
from typing import Any, ContextManager, Generator, Mapping, Protocol

Row = Mapping[str, Any]


class Jobs(Protocol):
    def get(self, job_id: int) -> Row | None: ...
    def by_source(self, source: str, external_id: str) -> Row | None: ...
    def active(self, *, is_demo: bool | None = None, source: str | None = None,
               visibility: str = 'all', org_id: int | None = None) -> list[Row]: ...
    def iter_active(self, *, is_demo: bool | None = None, source: str | None = None,
                    visibility: str = 'all', org_id: int | None = None,
                    requirement_evidence_only: bool = False) -> Generator[Row, None, None]: ...
    def active_page(self, *, offset: int, limit: int, is_demo: bool | None = None,
                    source: str | None = None, visibility: str = 'all',
                    org_id: int | None = None) -> tuple[list[Row], int]: ...
    def raw_inputs(self, ids: list[int]) -> dict[int, str]: ...
    def company(self, org_id: int) -> list[Row]: ...
    def public(self, is_demo: bool, status: str) -> list[Row]: ...
    def metadata(self, ids: list[int]) -> dict[int, Row]: ...
    def active_source(self, source: str) -> list[Row]: ...
    def insert(self, values: dict) -> int: ...
    def update(self, job_id: int, values: dict) -> None: ...
    def flags(self, job_id: int, published: bool, active: bool) -> None: ...
    def lifecycle(self, job_id: int, manual_inactive: bool, reason: str, stamp: str) -> None: ...
    def deactivate(self, job_id: int, run_id: int, stamp: str) -> None: ...
    def add_revision(self, job_id: int, run_id: int, stamp: str, payload: str, raw: str) -> None: ...
    def revisions(self, job_id: int) -> list[Row]: ...


class Runs(Protocol):
    def create(self, stamp: str, source: str, label: str, status: str, result: str, org_id: int | None = None) -> int: ...
    def finish(self, run_id: int, status: str, result: str) -> None: ...
    def recent(self, actor: Row | None) -> list[Row]: ...


class AccountRows(Protocol):
    def organization(self, name: str) -> int: ...
    def org_name(self, org_id: int) -> str: ...
    def by_username(self, username: str) -> Row | None: ...
    def get(self, user_id: int) -> Row | None: ...
    def create(self, values: dict) -> int: ...
    def expire_sessions(self, timestamp: float) -> None: ...
    def create_session(self, token_hash: str, user_id: int, expires: float) -> None: ...
    def session_user(self, token_hash: str, timestamp: float) -> Row | None: ...
    def delete_session(self, token_hash: str) -> None: ...
    def members(self, org_id: int) -> list[Row]: ...
    def grant(self, user_id: int, org_id: int, allowed: bool) -> bool: ...
    def favorites(self, user_id: int) -> dict[int, str]: ...
    def save_favorite(self, user_id: int, job_id: int, note: str | None, remove: bool) -> None: ...


class ReviewRows(Protocol):
    def fields(self, ids: list[int]) -> dict[tuple[int, str], Row]: ...
    def field(self, job_id: int, field: str) -> Row | None: ...
    def save_field(self, job_id: int, field: str, values: dict) -> None: ...
    def decisions(self) -> dict[tuple[int, int], Row]: ...
    def decision(self, left_id: int, right_id: int) -> Row | None: ...
    def save_decision(self, left_id: int, right_id: int, values: dict) -> None: ...


class ResumeRows(Protocol):
    def metadata(self, user_id: int) -> Row | None: ...
    def get(self, user_id: int) -> Row | None: ...
    def save(self, user_id: int, values: dict) -> None: ...


class AuditRows(Protocol):
    def append(self, actor: Row, action: str, target: str, details: dict | None = None) -> None: ...
    def recent(self, actor: Row) -> list[Row]: ...


class Transaction(Protocol):
    jobs: Jobs
    runs: Runs
    accounts: AccountRows
    reviews: ReviewRows
    audit: AuditRows
    resumes: ResumeRows


class UnitOfWork(Protocol):
    def __call__(self, *, write: bool = False) -> ContextManager[Transaction]: ...


class JobReadModels(Protocol):
    def jobs_in(self, tx: Transaction, filters: dict, actor: Row) -> list[dict]: ...
    def detail_in(self, tx: Transaction, job_id: int, actor: Row) -> dict | None: ...


class AccountContext(Protocol):
    uow: UnitOfWork
    queries: JobReadModels
